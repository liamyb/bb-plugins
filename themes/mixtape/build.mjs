// Builds Mixtape's theme.css from four parts:
//   1. the two pixel fonts, embedded so the theme works offline,
//   2. palette.css (Mixtape's colours and type),
//   3. Sandbar's layout rules, copied from ../sandbar/theme.css, everything
//      from the "Taller top bar" block on (the top bar, the toggles, the
//      Mac frame, pane attention and families, the rail, sliding panes),
//   4. skin.css (the retro chrome on top).
// Sandbar stays the one place the layout lives: after changing it, run
// `node build.mjs` and `bb theme set mixtape` to bring Mixtape up to date.
//
// Usage: node build.mjs [--sandbar <path>] [--out <path>]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const sandbarPath = arg("--sandbar", join(here, "..", "sandbar", "theme.css"));
const outPath = arg("--out", join(here, "theme.css"));

const sandbar = readFileSync(sandbarPath, "utf8");
const marker = "/*\n * Taller top bar";
const start = sandbar.indexOf(marker);
if (start < 0) throw new Error(`No "Taller top bar" block in ${sandbarPath}; has Sandbar's layout moved?`);
const layout = sandbar.slice(start).trimEnd();

const font = (file) => readFileSync(join(here, "fonts", file)).toString("base64");
const fontFaces = `/*
 * Fonts, embedded so the theme needs no network (Latin subsets from Google
 * Fonts, unmodified):
 *   VT323, Copyright 2011 The VT323 Project Authors (peter.hull@oikoi.com)
 *   Silkscreen, Copyright 2001 The Silkscreen Project Authors
 *     (https://github.com/googlefonts/silkscreen)
 * Both are licensed under the SIL Open Font License, Version 1.1; the full
 * text is in fonts/OFL-VT323.txt and fonts/OFL-Silkscreen.txt beside
 * build.mjs, and at https://openfontlicense.org. VT323 is drawn small for
 * its size, so it's scaled up to sit level with the text around it.
 */
@font-face {
  font-family: "Mixtape VT";
  src: url(data:font/woff2;base64,${font("vt323-latin.woff2")}) format("woff2");
  font-weight: 400;
  font-style: normal;
  font-display: block;
  size-adjust: 112%;
}

@font-face {
  font-family: "Mixtape Pixel";
  src: url(data:font/woff2;base64,${font("silkscreen-400-latin.woff2")}) format("woff2");
  font-weight: 400;
  font-style: normal;
  font-display: block;
}`;

const banner = `/*
 * Mixtape - a late-90s desktop media player for bb: brushed-silver chrome
 * and raised keys round dark panels, with green LCD readouts and purple
 * selection, the same in light and dark mode. An original look, not a copy of any player's skin. Code colours
 * come from theme.json beside this file (dark in both modes).
 *
 * GENERATED by build.mjs from palette.css, skin.css and Sandbar's layout.
 * Edit those and rebuild; edits made here are lost on the next build.
 *
 * Switch back to Sandbar with \`bb theme set sandbar\`, or pick it in
 * Settings > Appearance.
 */`;

const css = [
  banner,
  fontFaces,
  readFileSync(join(here, "palette.css"), "utf8").trim(),
  `/* ====================================================================
 * Sandbar's layout, copied by build.mjs from themes/sandbar/theme.css.
 * Change it there, not here.
 * ==================================================================== */`,
  layout,
  `/* ====================================================================
 * Mixtape's skin (skin.css).
 * ==================================================================== */`,
  readFileSync(join(here, "skin.css"), "utf8").trim(),
].join("\n\n") + "\n";

writeFileSync(outPath, css);
console.log(`${outPath}: ${(css.length / 1024).toFixed(1)} KB`);
