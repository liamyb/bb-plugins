// Builds Palm Noir's theme.css from four parts:
//   1. the pictures, embedded as SVG so the theme needs no image files: the
//      rail's scene (scene.mjs) and the wallpaper behind the threads
//      (wallpaper.mjs), each still and moving,
//   2. palette.css (Palm Noir's colours and type),
//   3. Sandbar's layout rules, copied from ../sandbar/theme.css, everything
//      from the "Taller top bar" block on (the top bar, the toggles, the
//      Mac frame, pane attention and families, the rail, sliding panes),
//   4. skin.css (the look on top).
// Sandbar stays the one place the layout lives: after changing it, run
// `node build.mjs` and `bb theme set palm-noir` to bring Palm Noir up to date.
//
// Usage: node build.mjs [--sandbar <path>] [--out <path>]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sceneUrl } from "./scene.mjs";
import { horizon, palmsLeft, palmsRight, stars, toUrl, MODES } from "./wallpaper.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const sandbarPath = arg("--sandbar", join(here, "..", "sandbar", "theme.css"));
const outPath = arg("--out", join(here, "theme.css"));

const sandbar = readFileSync(sandbarPath, "utf8");
const marker = "/*\n * Taller top bar";
const start = sandbar.indexOf(marker);
if (start < 0) throw new Error(`No "Taller top bar" block in ${sandbarPath}; has Sandbar's layout moved?`);
const layout = sandbar.slice(start).trimEnd();

const banner = `/*
 * Palm Noir - a coast at dusk for bb: night-sky bars with a neon horizon,
 * titles lit like signs, a sunset down the rail with a sun, the sea and two
 * palms at its foot, the same coast as a wallpaper behind the threads, and
 * calm panels to read (shell-white in light mode, violet night in dark). An original look. Code colours come from
 * theme.json beside this file.
 *
 * GENERATED by build.mjs from palette.css, skin.css, scene.mjs,
 * wallpaper.mjs and Sandbar's layout. Edit those and rebuild; edits made
 * here are lost on the next build.
 *
 * Switch back to Sandbar with \`bb theme set sandbar\`, or pick it in
 * Settings > Appearance.
 */`;

const scene = `/* The rail's scene (scene.mjs): still, and moving while agents work. */
:root {
  --pn-scene: ${sceneUrl(false)};
  --pn-scene-live: ${sceneUrl(true)};
}`;

const wall = (mode, live) => `
  --pn-wall-sky: ${MODES[mode].sky};
  --pn-wall-horizon: ${toUrl(horizon(mode, live))};
  --pn-wall-left: ${toUrl(palmsLeft(mode))};
  --pn-wall-right: ${toUrl(palmsRight(mode))};
  --pn-wall-stars: ${mode === "dark" ? toUrl(stars(live)) : "none"};`;

// Which wallpaper light mode gets. "dark" (Liam's choice, 18 Nov) shows the
// neon night in both modes; "light" brings back the golden-hour dusk.
const LIGHT_MODE_WALLPAPER = "dark";

const oneWallpaper = LIGHT_MODE_WALLPAPER === "dark";
const wallpaper = `/*
 * The wallpaper behind the threads (wallpaper.mjs): ${oneWallpaper ? "a neon night with stars\n * in both modes" : "a neon night with stars\n * in dark mode and a golden-hour dusk in light"}, moving gently unless macOS has Reduce
 * motion on.
 */
${oneWallpaper ? ":root, .light, .dark" : ":root, .light"} {${wall(LIGHT_MODE_WALLPAPER, true)}
}
${oneWallpaper ? "" : `
.dark {${wall("dark", true)}
}
`}
@media (prefers-reduced-motion: reduce) {
  ${oneWallpaper ? ":root, .light, .dark" : ":root, .light"} {
    --pn-wall-horizon: ${toUrl(horizon(LIGHT_MODE_WALLPAPER, false))};${LIGHT_MODE_WALLPAPER === "dark" ? `
    --pn-wall-stars: ${toUrl(stars(false))};` : ""}
  }${oneWallpaper ? "" : `

  .dark {
    --pn-wall-horizon: ${toUrl(horizon("dark", false))};
    --pn-wall-stars: ${toUrl(stars(false))};
  }`}
}`;

const css = [
  banner,
  scene,
  wallpaper,
  readFileSync(join(here, "palette.css"), "utf8").trim(),
  `/* ====================================================================
 * Sandbar's layout, copied by build.mjs from themes/sandbar/theme.css.
 * Change it there, not here.
 * ==================================================================== */`,
  layout,
  `/* ====================================================================
 * Palm Noir's skin (skin.css).
 * ==================================================================== */`,
  readFileSync(join(here, "skin.css"), "utf8").trim(),
].join("\n\n") + "\n";

writeFileSync(outPath, css);
console.log(`${outPath}: ${(css.length / 1024).toFixed(1)} KB`);
