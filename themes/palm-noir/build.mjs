// Builds Palm Noir's theme.css from four parts:
//   1. the rail's scene, drawn by scene.mjs and embedded as SVG, still and
//      moving, so the theme needs no image files,
//   2. palette.css (Palm Noir's colours and type),
//   3. Sandbar's layout rules, copied from ../sandbar/theme.css, everything
//      from the "Taller top bar" block on (the top bar, the toggles, the
//      Mac frame, pane attention and families, the rail, sliding panes),
//   4. skin.css (the look on top).
// Sandbar stays the one place the layout lives: after changing it, run
// `node build.mjs` and `bb theme set palm-noir` to bring Palm Noir up to date.
//
// Usage: node build.mjs [--sandbar <path>] [--out <path>]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sceneUrl } from "./scene.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const sandbarPath = arg("--sandbar", join(here, "..", "sandbar", "theme.css"));
const outPath = arg("--out", join(here, "theme.css"));

const sandbar = readFileSync(sandbarPath, "utf8");
const marker = "/*\n * Taller top bar";
const start = sandbar.indexOf(marker);
if (start < 0) throw new Error(`No "Taller top bar" block in ${sandbarPath}; has Sandbar's layout moved?`);
const layout = sandbar.slice(start).trimEnd();

const banner = `/*
 * Palm Noir - a coast at dusk for bb: night-sky bars with a neon horizon,
 * titles lit like signs, a sunset down the rail with a sun, the sea and two
 * palms at its foot, and calm panels to read (shell-white in light mode,
 * violet night in dark). An original look. Code colours come from
 * theme.json beside this file.
 *
 * GENERATED by build.mjs from palette.css, skin.css, scene.mjs and
 * Sandbar's layout. Edit those and rebuild; edits made here are lost on the
 * next build.
 *
 * Switch back to Sandbar with \`bb theme set sandbar\`, or pick it in
 * Settings > Appearance.
 */`;

const scene = `/* The rail's scene (scene.mjs): still, and moving while agents work. */
:root {
  --pn-scene: ${sceneUrl(false)};
  --pn-scene-live: ${sceneUrl(true)};
}`;

const css = [
  banner,
  scene,
  readFileSync(join(here, "palette.css"), "utf8").trim(),
  `/* ====================================================================
 * Sandbar's layout, copied by build.mjs from themes/sandbar/theme.css.
 * Change it there, not here.
 * ==================================================================== */`,
  layout,
  `/* ====================================================================
 * Palm Noir's skin (skin.css).
 * ==================================================================== */`,
  readFileSync(join(here, "skin.css"), "utf8").trim(),
].join("\n\n") + "\n";

writeFileSync(outPath, css);
console.log(`${outPath}: ${(css.length / 1024).toFixed(1)} KB`);
